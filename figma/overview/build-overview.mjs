// Code Connect overview: reads every template in figma/ (components, icons, logos, flags) and writes
// src/lib/codeConnect.json – the table on /styleguide#code-connect and the Figma page „🔗 Code Connect“ use it.
// Usage: node figma/overview/build-overview.mjs (write) · --check (exit 1 if the JSON is out of date, part of figma:check)
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";

const root = new URL("../../", import.meta.url);
const target = new URL("src/lib/codeConnect.json", root);
const KINDS = { components: "component", icons: "icon", logos: "logo", flags: "flag" };
// Area of a component in the overview, from the folder of its source file
const AREAS = {
  ui: "Basis",
  layout: "Layout",
  cards: "Karten",
  brand: "Karten",
  coaches: "Karten",
  events: "Events",
  play: "Events",
  locations: "Standorte",
  modules: "Module",
  home: "Module",
  a11y: "Barrierefreiheit",
};

// Components whose folder does not name their area
const AREA_OVERRIDES = { SectionIntro: "Module", OpenStatus: "Standorte" };

const PROP_KINDS = { getString: "Text", getEnum: "Variante", getBoolean: "Boolean", getInstanceSwap: "Instance Swap", findText: "Textebene" };

// Figma names of the asset components follow the file names (icon/app/bar ← app-bar.figma.ts)
const assetName = (kind, base) =>
  kind === "icon" ? `icon/${base.replace("-", "/")}` : kind === "logo" ? `logo/${base}` : kind === "flag" ? `flag/${base.replace("-", "_")}` : base;

const header = (src, key) => src.match(new RegExp(`^// ${key}=(.*)$`, "m"))?.[1].trim();

const entries = [];
for (const [dir, kind] of Object.entries(KINDS)) {
  for (const file of readdirSync(new URL(`figma/${dir}/`, root)).filter((f) => f.endsWith(".figma.ts")).sort()) {
    const src = readFileSync(new URL(`figma/${dir}/${file}`, root), "utf8");
    const url = header(src, "url");
    const source = header(src, "source");
    const entry = {
      kind,
      id: src.match(/^\s*id: '([^']+)'/m)?.[1],
      code: header(src, "component"),
      figma: header(src, "figma") ?? assetName(kind, file.replace(".figma.ts", "")),
      nodeId: url.match(/node-id=(\d+)-(\d+)/).slice(1).join(":"),
      url,
      source,
      imports: [...src.matchAll(/'(import [^']+)'/g)].map((m) => m[1]),
    };
    // Asset templates are one-liners: the example is the whole mapping
    if (kind !== "component") entry.example = src.match(/figma\.code`([^`\n]+)`/)?.[1];
    if (kind === "component") {
      const folder = source.split("/").at(-2);
      entry.area = AREA_OVERRIDES[entry.code] ?? AREAS[folder] ?? "Basis";
      // Figma properties the template reads, with their kind
      const reads = [...src.matchAll(/instance\.(getString|getEnum|getBoolean|getInstanceSwap|findText)\('([^']+)'/g)];
      entry.props = [...new Map(reads.map(([, fn, name]) => [name, { name, kind: PROP_KINDS[fn] }])).values()];
      // Notes: the comment lines between the header and the export
      entry.notes = src
        .split("export default")[0]
        .split("\n")
        .filter((l) => l.startsWith("//") && !/^\/\/ (url|source|component|figma)=/.test(l))
        .map((l) => l.replace(/^\/\/\s?/, ""))
        .join(" ");
    }
    entries.push(entry);
  }
}

// The code side of every template must exist: source file, imported modules and the imported names
const codeErrors = [];
const resolveModule = (spec) => {
  if (!spec.startsWith("@/")) return null; // packages (lucide-react) are checked by tsc
  const base = new URL(`src/${spec.slice(2)}`, root).pathname;
  return [".tsx", ".ts", "/index.tsx", "/index.ts"].map((ext) => base + ext).find((p) => existsSync(p));
};
for (const e of entries) {
  if (!e.source.startsWith("node_modules/") && !existsSync(new URL(e.source, root))) codeErrors.push(`${e.figma}: source ${e.source} fehlt`);
  for (const imp of e.imports) {
    const [, names, spec] = imp.match(/^import \{ ([^}]+) \} from "([^"]+)"/) ?? [];
    if (!spec) continue;
    const file = resolveModule(spec);
    if (spec.startsWith("@/") && !file) { codeErrors.push(`${e.figma}: Modul ${spec} fehlt`); continue; }
    if (!file) continue;
    const code = readFileSync(file, "utf8");
    for (const name of names.split(",").map((n) => n.trim()))
      if (!new RegExp(`export (async )?(function|const|class|type) ${name}\\b|export \\{[^}]*\\b${name}\\b`).test(code)) codeErrors.push(`${e.figma}: ${name} wird von ${spec} nicht exportiert`);
  }
}
if (codeErrors.length) {
  console.log(`Code Connect zeigt auf Code, den es nicht gibt:\n  ${codeErrors.join("\n  ")}`);
  process.exit(1);
}

// Code Connect ids must be unique (they also key the styleguide list)
const ids = entries.map((e) => e.id);
const dupes = ids.filter((id, i) => !id || ids.indexOf(id) !== i);
if (dupes.length) {
  console.log(`Fehlende oder doppelte Code-Connect-ids: ${dupes.join(", ")}`);
  process.exit(1);
}

const json =
  JSON.stringify(
    {
      $comment: "Generated by figma/overview/build-overview.mjs from figma/**/*.figma.ts – do not edit by hand.",
      file: "n3QOz0mQUCyzzVmxX4nKw3",
      entries,
    },
    null,
    2,
  ) + "\n";

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {}
  if (current !== json) {
    console.log("src/lib/codeConnect.json ist veraltet – node figma/overview/build-overview.mjs ausführen.");
    process.exit(1);
  }
  console.log(`Code-Connect-Übersicht aktuell (${entries.length} Einträge).`);
} else {
  writeFileSync(target, json);
  const count = (k) => entries.filter((e) => e.kind === k).length;
  console.log(`src/lib/codeConnect.json: ${count("component")} Komponenten, ${count("icon")} Icons, ${count("logo")} Logos, ${count("flag")} Flaggen.`);
}
