/** Polish plural: 1 klub · 2–4 kluby · 5+ klubów (12–14 → klubów). */
function plClubs(n: number) {
  if (n === 1) return "klub";
  const d = n % 10;
  const dd = n % 100;
  return d >= 2 && d <= 4 && (dd < 12 || dd > 14) ? "kluby" : "klubów";
}

